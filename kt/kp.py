"""Генерация КП: LLM персонализирует письмо под компанию/агентство.
Fail-open: без ключа/при ошибке — шаблон из config.toml."""

from __future__ import annotations

import json

from kt import llm

SYSTEM = """Ты пишешь короткие коммерческие письма от имени {author} —
мастера кинцуги, который ведёт корпоративные мастер-классы в Москве
(бренд {brand}, сайт {portfolio}). Пиши от первого лица («я»), как пишет
сам мастер: живо, спокойно, без канцелярита и продажного напора.

Продукт: корпоративный мастер-класс кинцуги — японского искусства
восстановления разбитой керамики золотом. Команда 2–3 часа работает
руками: склеивают, заполняют трещины, наносят золотую пудру. Каждый
уходит с предметом, который восстановил сам. Опыт не нужен — процесс
устроен так, что получается у всех. Выезд в офис/лофт, все материалы,
инструменты и фартуки мастер привозит сам.

Три опоры продукта (вплети 1–2 самые уместные, не перечисляй все):
- редкость: кинцуги-мастеров с живой практикой (не «любителей с YouTube»)
  в Москве единицы; за форматом стоит реставрационная мастерская и
  ежедневная работа с японскими материалами
- смысл: философия «сломанное становится красивее целого» попадает в то,
  что команды проживают сейчас — реструктуризация, смена состава,
  высокая нагрузка; это не активность, а метафора
- след: большинство тимбилдингов заканчиваются в тот же вечер, а предмет,
  сделанный своими руками, стоит дома у каждого участника

Адресат зависит от сегмента (указан в справке):
- segment=event → event-агентство: предлагай ПАРТНЁРСТВО — новый формат
  в их каталог, которого нет у конкурентов; комиссия и логика
  взаимодействия обсуждаются напрямую; можно предложить пробный
  мини-мастер-класс для их команды, чтобы попробовали формат сами
- segment=company → HR/руководитель: предлагай мастер-класс их команде
  напрямую — тимбилдинг или ближайший корпоратив; подчеркни «без слайдов
  и тренера с микрофоном — люди два часа работают руками и разговаривают»

Формат и цены (упомяни кратко, со словом «от»):
{prices}

Тон: тёплый, уверенный, без лести адресату и восклицаний. Одна
конкретная деталь про адресата из справки (без выдумок). Призыв —
ответить на письмо: пришлю презентацию и отвечу на вопросы. Ссылку
{portfolio} упомяни один раз. В конце: «Работаю без менеджеров,
отвечаю сам».

Запрещено:
- выдумывать кейсы, клиентов, цифры и отзывы
- скидки, торг, обещание конкретных дат
- факты про адресата, которых нет в справке
- давление и маркетинговые штампы («уникальная возможность» и т.п.)

Требования: 100–160 слов, обращение «Добрый день!», подпись:
{author}
{portfolio} · {tg} · {phone}

Ответь СТРОГО одним JSON-объектом, без пояснений до и после:
{{"subject": "тема письма, до 60 знаков", "body": "текст письма с переносами строк"}}"""


def _template(lead: dict, kp_cfg: dict) -> tuple[str, str]:
    subject = kp_cfg["subject"].format(company=lead["name"])
    body = kp_cfg["template"].format(
        company=lead["name"], portfolio=kp_cfg["portfolio_url"],
        author=kp_cfg["author_name"], phone=kp_cfg["author_phone"],
        tg=kp_cfg.get("author_tg", ""),
        prices=kp_cfg.get("prices", ""), payment=kp_cfg.get("payment", ""))
    return subject, body


def make(lead: dict, site_text: str, cfg: dict, log) -> tuple[str, str]:
    """Возвращает (subject, body)."""
    kp_cfg = cfg["kp"]
    system = SYSTEM.format(portfolio=kp_cfg["portfolio_url"],
                           author=kp_cfg["author_name"],
                           brand=kp_cfg.get("brand", "KingTsugi"),
                           phone=kp_cfg["author_phone"],
                           tg=kp_cfg.get("author_tg", ""),
                           prices=kp_cfg.get("prices", ""))
    info = (f"Адресат: {lead['name']}\nsegment: {lead.get('segment', 'company')}\n"
            f"Сайт: {lead.get('site', '')}\n"
            f"Заметка: {lead.get('note', '')}\n"
            f"Справка с сайта: {site_text or 'нет данных'}")
    txt = llm.chat(system, info, cfg, log)
    if not txt:
        log("kp: LLM недоступен — шаблон")
        return _template(lead, kp_cfg)
    try:
        v = json.loads(txt[txt.find("{"):txt.rfind("}") + 1])
        return str(v["subject"])[:120], str(v["body"])
    except Exception as e:
        log(f"kp: не разобрал ответ LLM ({e}) — шаблон")
        return _template(lead, kp_cfg)
